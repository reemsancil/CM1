const assert = require('node:assert/strict');
const fs = require('node:fs');
const { JSDOM } = require('jsdom');
(async () => {
  const dom = new JSDOM('<form><label for="name">Name</label><select id="name" name="student_name" required></select><label for="section">Class</label><select id="section" name="class_section" required><option value=""></option></select><button>Send</button></form>', { runScripts: 'outside-only' });
  const w = dom.window, form = w.document.querySelector('form');
  w.eval(fs.readFileSync('gift-config.js', 'utf8'));
  w.eval(fs.readFileSync('student-roster.js', 'utf8'));
  const expected = { 'CP C':22, 'CP F':24, 'CE2 A':22, 'CE2 D':25, 'CM1 A':24, 'CM1 D':25 };
  const sections = w.GiftConfig.sections;
  for (const section of sections) form.elements.class_section.add(new w.Option(section, section));
  w.StudentRoster.bind(form, 'student_name', 'class_section');
  const names = form.elements.student_name, section = form.elements.class_section;
  assert.equal(form.querySelector('label').htmlFor, 'section');
  assert.equal(names.tagName, 'SELECT');
  assert.equal(names.options.length, 1);
  let submitted = 0;
  form.addEventListener('submit', event => { event.preventDefault(); submitted++; });
  for (const value of sections) {
    section.value = value;
    section.dispatchEvent(new w.Event('change'));
    const options = [...names.options].map(option => option.value).filter(Boolean);
    assert.equal(options.length, expected[value]);
    assert.equal(new Set(options).size, options.length);
    assert(options.every(name => name.trim() === name));
    assert.equal(names.value, '');
    names.value = options[0];
    form.dispatchEvent(new w.Event('submit', { cancelable: true }));
    assert.equal(submitted, sections.indexOf(value) + 1);
  }
  section.value = sections[0];
  section.dispatchEvent(new w.Event('change'));
  assert.equal(names.value, '');
  const before = submitted;
  names.add(new w.Option('Unregistered student', 'Unregistered student'));
  names.value = 'Unregistered student';
  form.dispatchEvent(new w.Event('submit', { cancelable: true }));
  assert.equal(submitted, before);
  assert(names.validationMessage.includes('registered name'));
  names.value = names.options[1].value;
  names.dispatchEvent(new w.Event('change'));
  assert.equal(names.validationMessage, '');
  form.reset();
  await Promise.resolve();
  assert.equal(section.value, '');
  assert.equal(names.value, '');
  assert.equal(names.options.length, 1);
  dom.window.close();
  console.log('Passed registered names: PDF counts, class isolation, class-first order, validation, class changes and reset.');
})().catch(error => { console.error(error); process.exitCode = 1; });
